const domainInput = document.getElementById('domain')
const botInput = document.getElementById('botUsername')
const statusEl = document.getElementById('status')

const DEFAULT_BOT = 'Dwnldr276bot'

function setStatus(msg) { statusEl.textContent = msg }

/** Strips protocol/path/leading "www." so "https://www.youtube.com/watch?…"
 *  and "youtube.com" both resolve to the same registrable domain. This
 *  matters: chrome.cookies.getAll({domain}) only matches that domain or its
 *  SUBdomains, so "www.youtube.com" misses the ".youtube.com"-scoped auth
 *  cookies Google actually sets. */
function cleanDomain(raw) {
  return raw.trim().replace(/^https?:\/\//, '').replace(/\/.*$/, '').replace(/^www\./, '')
}

// Prefill domain from the active tab, and bot username from storage.
;(async () => {
  const { botUsername, lastDomain } = await chrome.storage.local.get(['botUsername', 'lastDomain'])
  botInput.value = botUsername || DEFAULT_BOT
  if (lastDomain) {
    domainInput.value = cleanDomain(lastDomain)
  } else {
    try {
      const [tab] = await chrome.tabs.query({ active: true, currentWindow: true })
      if (tab?.url) domainInput.value = cleanDomain(new URL(tab.url).hostname)
    } catch { /* ignore */ }
  }
})()

botInput.addEventListener('change', () => {
  chrome.storage.local.set({ botUsername: botInput.value.trim() || DEFAULT_BOT })
})

function netscapeDate(expirationDate) {
  return expirationDate ? Math.round(expirationDate) : 0
}

/** Netscape cookies.txt format — what yt-dlp and the MediaDL bot's /cookies expect. */
function toNetscapeCookies(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by MediaDL Cookie Sync']
  for (const c of cookies) {
    lines.push([
      c.domain,
      c.domain.startsWith('.') ? 'TRUE' : 'FALSE',
      c.path,
      c.secure ? 'TRUE' : 'FALSE',
      netscapeDate(c.expirationDate),
      c.name,
      c.value,
    ].join('\t'))
  }
  return lines.join('\n') + '\n'
}

async function getCookiesForDomain(domain) {
  const patterns = [`*://${domain}/*`, `*://*.${domain}/*`]
  const granted = await chrome.permissions.request({ origins: patterns })
  if (!granted) throw new Error('Permission to read this site\'s cookies was denied.')
  const cookies = await chrome.cookies.getAll({ domain })
  if (!cookies.length) throw new Error(`No cookies found for ${domain} — are you logged in there?`)
  return cookies
}

document.getElementById('sendBtn').addEventListener('click', async () => {
  const domain = cleanDomain(domainInput.value)
  if (!domain) return setStatus('Enter a domain first, e.g. youtube.com')
  const bot = (botInput.value.trim() || DEFAULT_BOT)
  await chrome.storage.local.set({ lastDomain: domain, botUsername: bot })
  setStatus('Reading cookies…')
  try {
    const cookies = await getCookiesForDomain(domain)
    const text = toNetscapeCookies(cookies)
    await navigator.clipboard.writeText(text)
    await chrome.tabs.create({ url: `https://t.me/${bot}` })
    setStatus(
      `✅ Copied ${cookies.length} cookies for ${domain}.\n\n` +
      `In the chat that just opened, send:\n/cookies add ${domain}\n\n` +
      `Then paste (Ctrl+V) as your next message.`,
    )
  } catch (e) {
    setStatus(`❌ ${e.message}`)
  }
})

document.getElementById('downloadBtn').addEventListener('click', async () => {
  const domain = cleanDomain(domainInput.value)
  if (!domain) return setStatus('Enter a domain first, e.g. youtube.com')
  await chrome.storage.local.set({ lastDomain: domain })
  setStatus('Reading cookies…')
  try {
    const cookies = await getCookiesForDomain(domain)
    const text = toNetscapeCookies(cookies)
    const url = URL.createObjectURL(new Blob([text], { type: 'text/plain' }))
    await chrome.downloads.download({ url, filename: `${domain}-cookies.txt`, saveAs: true })
    setStatus(`✅ Downloaded ${cookies.length} cookies for ${domain}.`)
  } catch (e) {
    setStatus(`❌ ${e.message}`)
  }
})
