// Shared by the background script, popup and options page (classic script —
// loaded via importScripts() in the Chromium service worker and via <script>
// / background.scripts elsewhere, so it must not use import/export).
//
// `ext` is the WebExtension API: Firefox exposes promise-based `browser`,
// Chromium exposes `chrome` (promise-based in MV3 when no callback is given).
/* eslint-disable no-var */
var ext = globalThis.browser ?? globalThis.chrome

var DEFAULT_SETTINGS = {
  serverUrl:      'http://localhost:4000',
  kind:           'video',   // 'video' | 'audio'
  videoFormat:    'mp4',
  audioFormat:    'mp3',
  quality:        'best',
  subtitles:      false,
  embedThumbnail: true,
  sponsorBlock:   false,
  autoSave:       true,      // save finished files into the browser's Downloads folder
  notify:         true,
  botUsername:    'Dwnldr276bot',
}

async function getSettings() {
  const saved = await ext.storage.sync.get(Object.keys(DEFAULT_SETTINGS))
  return { ...DEFAULT_SETTINGS, ...saved }
}

async function serverBase() {
  const { serverUrl } = await getSettings()
  return (serverUrl || DEFAULT_SETTINGS.serverUrl).trim().replace(/\/+$/, '')
}

/** JSON request to the MediaDL server. Throws Error with the server's message. */
async function api(path, { method = 'GET', body, timeoutMs = 60_000 } = {}) {
  const base = await serverBase()
  const ctrl = new AbortController()
  const timer = setTimeout(() => ctrl.abort(), timeoutMs)
  let res
  try {
    res = await fetch(base + path, {
      method,
      headers: body ? { 'Content-Type': 'application/json' } : undefined,
      body: body ? JSON.stringify(body) : undefined,
      signal: ctrl.signal,
    })
  } catch (e) {
    throw new Error(e.name === 'AbortError'
      ? 'The server took too long to answer.'
      : `Can't reach MediaDL at ${base} — is it running? (npm run dev)`)
  } finally { clearTimeout(timer) }
  let data = null
  try { data = await res.json() } catch { /* empty / non-JSON body */ }
  if (!res.ok) throw new Error((data && (data.error || data.detail)) || `Server error ${res.status}`)
  return data
}

function fileUrl(base, jobId, name) {
  return `${base}/api/files/${jobId}/${encodeURIComponent(name)}`
}

/** Build the POST /api/download body from a URL + settings (+ overrides). */
function buildDownload(url, s, extra = {}) {
  const audio = s.kind === 'audio'
  return {
    url,
    mediaType:      'video',
    format:         audio ? s.audioFormat : s.videoFormat,
    quality:        audio ? 'best' : s.quality,
    subtitles:      !audio && !!s.subtitles,
    embedThumbnail: !!s.embedThumbnail,
    embedMetadata:  true,
    sponsorBlock:   !!s.sponsorBlock,
    ...extra,
  }
}

function isHttpUrl(u) { return typeof u === 'string' && /^https?:\/\//i.test(u) }

function fmtBytes(n) {
  if (!n && n !== 0) return ''
  const u = ['B', 'KB', 'MB', 'GB', 'TB']; let i = 0
  while (n >= 1024 && i < u.length - 1) { n /= 1024; i++ }
  return `${n.toFixed(n >= 10 || i === 0 ? 0 : 1)} ${u[i]}`
}

function fmtDuration(sec) {
  if (!sec) return ''
  sec = Math.round(sec)
  const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = sec % 60
  return (h ? `${h}:${String(m).padStart(2, '0')}` : `${m}`) + `:${String(s).padStart(2, '0')}`
}

/** Strip protocol/path/"www." — cookies.getAll({domain}) matches that domain
 *  and its subdomains, so "youtube.com" also catches ".youtube.com" cookies. */
function cleanDomain(raw) {
  return (raw || '').trim().replace(/^https?:\/\//i, '').replace(/[/:?#].*$/, '').replace(/^www\./i, '').toLowerCase()
}

/** Netscape cookies.txt — the format yt-dlp, the server and the bot accept. */
function toNetscapeCookies(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by the MediaDL extension']
  for (const c of cookies) {
    lines.push([
      c.domain,
      c.domain.startsWith('.') ? 'TRUE' : 'FALSE',
      c.path,
      c.secure ? 'TRUE' : 'FALSE',
      c.expirationDate ? Math.round(c.expirationDate) : 0,
      c.name,
      c.value,
    ].join('\t'))
  }
  return lines.join('\n') + '\n'
}

/** Read a site's cookies, asking for per-site permission first (optional host
 *  permission — the extension can't read any cookies until you allow a site). */
async function readCookies(domain) {
  const origins = [`*://${domain}/*`, `*://*.${domain}/*`]
  const ok = await ext.permissions.request({ origins })
  if (!ok) throw new Error(`Permission to read ${domain} cookies was denied.`)
  const cookies = await ext.cookies.getAll({ domain })
  if (!cookies.length) throw new Error(`No cookies for ${domain} — are you logged in there?`)
  return cookies
}
